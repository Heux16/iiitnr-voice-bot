"""Citation utilities used by the UI runtime and evaluator."""

from __future__ import annotations

import re

_CITATION_START_RE = re.compile(r"(?:page|halaman)\s*:?\s*(?=\d)", re.IGNORECASE)
_NUMBER_RE = re.compile(r"\d{1,4}")
_SEPARATOR_RE = re.compile(r"\s*(,|and|dan|to|s\.?d\.?|[-–—])\s*", re.IGNORECASE)
_MAX_RANGE_SPAN = 40


def extract_cited_pages(answer: str) -> list[int]:
    """
    Extract page numbers from citation text in an answer.

    Supports "Page 48", "Page 39-41", and "Page 39, 40 and 41" (and legacy Indonesian).
    A dash followed by a smaller number is treated as a heading separator rather than
    a range; this prevents `Page 43 — 5. Study load` from reading 5 as a page.
    """
    if not answer:
        return []

    pages: set[int] = set()
    for match in _CITATION_START_RE.finditer(answer):
        position = match.end()
        first = _NUMBER_RE.match(answer, position)
        if not first:
            continue

        current = int(first.group())
        pages.add(current)
        position = first.end()

        while True:
            separator = _SEPARATOR_RE.match(answer, position)
            if not separator:
                break
            following_match = _NUMBER_RE.match(answer, separator.end())
            if not following_match:
                break

            following = int(following_match.group())
            is_dash = separator.group(1) in {"-", "–", "—"}
            if is_dash:
                if following <= current or following - current > _MAX_RANGE_SPAN:
                    break
                pages.update(range(current, following + 1))
            else:
                pages.add(following)

            current = following
            position = following_match.end()

    return sorted(pages)


def citation_pages_are_in_context(answer: str, contexts) -> bool:
    """Ensure every cited page comes from the retrieved context."""
    cited = set(extract_cited_pages(answer))
    context_pages = {page for context in contexts for page in context.page_numbers}
    return bool(cited) and cited <= context_pages


def strip_inline_source_lines(answer: str) -> str:
    """
    Remove inline source lines generated by LLM from main display.

    The UI renders sources in a dedicated structured card below the answer.
    Removing inline lines prevents duplicate sources.
    """
    if not answer:
        return answer

    kept: list[str] = []
    for line in answer.splitlines():
        normalized = line.strip().lower()
        is_source_line = (
            ("source:" in normalized or "sumber:" in normalized)
            and ("page" in normalized or "halaman" in normalized)
        )
        if not is_source_line:
            kept.append(line)

    cleaned = "\n".join(kept)
    cleaned = re.sub(r"\n{3,}", "\n\n", cleaned)
    return cleaned.strip()
